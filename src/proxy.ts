import { type NextRequest, NextResponse } from "next/server";

import { serverLog } from "@/libs/serverLog";
import type { CurrentAuthResponseDTO } from "@/modules/auth/domain/dto/AuthResponseDTO";
import { AUTH_COOKIE } from "@/modules/auth/shared/constants/authCookie";
import { canAccessApi, canAccessRoute } from "@/security/fieldGuard";
import { evaluatePolicy } from "@/security/policyEngine";

//////////////////////////////////////////////////////////////
// PUBLIC PAGES
//////////////////////////////////////////////////////////////

const PUBLIC_PAGES = [
  "/login",
  "/register",
  "/forgot-password",
  "/reset-password",
  "/verify-email",
];

//////////////////////////////////////////////////////////////
// STATIC ASSET
//////////////////////////////////////////////////////////////

function isStaticAsset(pathname: string): boolean {
  return (
    pathname.startsWith("/_next") ||
    pathname.startsWith("/assets") ||
    pathname.startsWith("/images") ||
    pathname === "/favicon.ico"
  );
}

//////////////////////////////////////////////////////////////
// API ROUTE
//////////////////////////////////////////////////////////////

function isApiRoute(pathname: string): boolean {
  return pathname.startsWith("/api/v1");
}

//////////////////////////////////////////////////////////////
// ENGINE VALIDATION ROUTE (aksaventra_engine.exe)
//////////////////////////////////////////////////////////////

function isEngineValidationRoute(pathname: string): boolean {
  return (
    pathname === "/api/v1/validate" ||
    pathname === "/api/v1/validate-key" ||
    pathname.startsWith("/api/v1/validate/") ||
    pathname.startsWith("/api/v1/validate-key/") ||
    pathname.startsWith("/api/v1/engine/validate") ||
    pathname.startsWith("/api/v1/license/validate")
  );
}

//////////////////////////////////////////////////////////////
// PUBLIC ROUTE
//////////////////////////////////////////////////////////////

function isPublicRoute(pathname: string): boolean {
  return (
    ////////////////////////////////////////////////////////////
    // AUTH API
    ////////////////////////////////////////////////////////////
    pathname.startsWith("/api/v1/auth") ||
    ////////////////////////////////////////////////////////////
    // ENGINE VALIDATION API (Validated via License Key)
    ////////////////////////////////////////////////////////////
    isEngineValidationRoute(pathname) ||
    ////////////////////////////////////////////////////////////
    // PUBLIC PAGE
    ////////////////////////////////////////////////////////////
    PUBLIC_PAGES.some((route) => pathname === route || pathname.startsWith(`${route}/`))
  );
}

//////////////////////////////////////////////////////////////
// UNAUTHORIZED
//////////////////////////////////////////////////////////////

function unauthorized(request: NextRequest, message = "Unauthorized"): NextResponse {
  ////////////////////////////////////////////////////////////
  // API
  ////////////////////////////////////////////////////////////
  if (isApiRoute(request.nextUrl.pathname)) {
    return NextResponse.json(
      {
        success: false,
        message,
      },
      {
        status: 401,
      },
    );
  }

  ////////////////////////////////////////////////////////////
  // REDIRECT LOGIN
  ////////////////////////////////////////////////////////////
  const loginUrl = new URL("/login", request.url);
  loginUrl.searchParams.set("redirect", request.nextUrl.pathname);

  return NextResponse.redirect(loginUrl);
}

//////////////////////////////////////////////////////////////
// FORBIDDEN
//////////////////////////////////////////////////////////////

function forbidden(request: NextRequest, message = "Forbidden"): NextResponse {
  ////////////////////////////////////////////////////////////
  // API
  ////////////////////////////////////////////////////////////
  if (isApiRoute(request.nextUrl.pathname)) {
    return NextResponse.json(
      {
        success: false,
        message,
      },
      {
        status: 403,
      },
    );
  }

  ////////////////////////////////////////////////////////////
  // REWRITE
  ////////////////////////////////////////////////////////////
  return NextResponse.rewrite(new URL("/403", request.url));
}

//////////////////////////////////////////////////////////////
// VALIDATE ACCESS TOKEN
//////////////////////////////////////////////////////////////

async function validateAccessToken(request: NextRequest): Promise<CurrentAuthResponseDTO | null> {
  try {
    ////////////////////////////////////////////////////////////
    // ACCESS TOKEN
    ////////////////////////////////////////////////////////////
    const accessToken = request.cookies.get(AUTH_COOKIE.ACCESS_TOKEN)?.value;

    ////////////////////////////////////////////////////////////
    // INVALID TOKEN
    ////////////////////////////////////////////////////////////
    if (!accessToken) {
      return null;
    }

    ////////////////////////////////////////////////////////////
    // FETCH API
    ////////////////////////////////////////////////////////////
    const response = await fetch(new URL("/api/v1/auth/validate-access-token", request.url), {
      method: "GET",
      headers: {
        cookie: request.headers.get("cookie") ?? "",
        "user-agent": request.headers.get("user-agent") ?? "",
      },
      cache: "no-store",
    });

    ////////////////////////////////////////////////////////////
    // INVALID RESPONSE
    ////////////////////////////////////////////////////////////
    if (!response.ok) {
      return null;
    }

    ////////////////////////////////////////////////////////////
    // JSON
    ////////////////////////////////////////////////////////////
    const result = await response.json();

    ////////////////////////////////////////////////////////////
    // RESPONSE
    ////////////////////////////////////////////////////////////
    return result.data ?? null;
  } catch (error) {
    serverLog("[VALIDATE_ACCESS_TOKEN_ERROR]", error);
    return null;
  }
}

//////////////////////////////////////////////////////////////
// PROXY
//////////////////////////////////////////////////////////////

export async function proxy(request: NextRequest): Promise<NextResponse> {
  try {
    ////////////////////////////////////////////////////////////
    // PATHNAME
    ////////////////////////////////////////////////////////////
    const pathname = request.nextUrl.pathname;

    ////////////////////////////////////////////////////////////
    // STATIC BYPASS
    ////////////////////////////////////////////////////////////
    if (isStaticAsset(pathname)) {
      return NextResponse.next();
    }

    ////////////////////////////////////////////////////////////
    // ENGINE VALIDATION API (Validating aksaventra_engine.exe)
    ////////////////////////////////////////////////////////////
    if (isEngineValidationRoute(pathname)) {
      // 1. Direct validation routes accept JSON body payload (serial_key, hwid, engine_version)
      if (
        pathname === "/api/v1/validate" ||
        pathname === "/api/v1/validate-key" ||
        pathname.startsWith("/api/v1/validate/") ||
        pathname.startsWith("/api/v1/validate-key/")
      ) {
        return NextResponse.next();
      }

      // 2. Header-based license endpoints
      const licenseKey =
        request.headers.get("x-license-key") ??
        request.headers.get("authorization")?.replace(/^Bearer\s+/i, "");

      if (!licenseKey) {
        return NextResponse.json(
          {
            success: false,
            valid: false,
            message: "License key required for engine validation",
          },
          {
            status: 401,
          },
        );
      }

      const headers = new Headers(request.headers);
      headers.set("x-engine-license-key", licenseKey);
      headers.set("x-engine-client", "aksaventra_engine");

      return NextResponse.next({
        request: {
          headers,
        },
      });
    }

    ////////////////////////////////////////////////////////////
    // PUBLIC ROUTE
    ////////////////////////////////////////////////////////////
    if (isPublicRoute(pathname)) {
      //////////////////////////////////////////////////////////
      // AUTH PAGE
      //////////////////////////////////////////////////////////
      const isAuthPage = PUBLIC_PAGES.includes(pathname);

      if (isAuthPage) {
        ////////////////////////////////////////////////////////
        // COOKIES
        ////////////////////////////////////////////////////////
        const accessToken = request.cookies.get(AUTH_COOKIE.ACCESS_TOKEN)?.value;
        const refreshToken = request.cookies.get(AUTH_COOKIE.REFRESH_TOKEN)?.value;

        ////////////////////////////////////////////////////////
        // AUTHENTICATED
        ////////////////////////////////////////////////////////
        if (accessToken && refreshToken) {
          const user = await validateAccessToken(request);

          if (user) {
            return NextResponse.redirect(new URL("/dashboard", request.url));
          }
        }
      }

      //////////////////////////////////////////////////////////
      // ALLOW
      //////////////////////////////////////////////////////////
      return NextResponse.next();
    }

    ////////////////////////////////////////////////////////////
    // COOKIES
    ////////////////////////////////////////////////////////////
    const accessToken = request.cookies.get(AUTH_COOKIE.ACCESS_TOKEN)?.value;
    const refreshToken = request.cookies.get(AUTH_COOKIE.REFRESH_TOKEN)?.value;

    ////////////////////////////////////////////////////////////
    // UNAUTHORIZED
    ////////////////////////////////////////////////////////////
    if (!accessToken || !refreshToken) {
      return unauthorized(request, "Authentication required");
    }

    ////////////////////////////////////////////////////////////
    // VALIDATE TOKEN
    ////////////////////////////////////////////////////////////
    const user = await validateAccessToken(request);

    ////////////////////////////////////////////////////////////
    // INVALID TOKEN
    ////////////////////////////////////////////////////////////
    if (!user) {
      const response = unauthorized(request, "Invalid or expired token");

      //////////////////////////////////////////////////////////
      // CLEAR COOKIE
      //////////////////////////////////////////////////////////
      response.cookies.delete(AUTH_COOKIE.ACCESS_TOKEN);
      response.cookies.delete(AUTH_COOKIE.REFRESH_TOKEN);

      return response;
    }

    ////////////////////////////////////////////////////////////
    // AUTH CONTEXT (Aksaventra Engine & Admin Scope)
    ////////////////////////////////////////////////////////////
    const auth = {
      //////////////////////////////////////////////////////////
      // USER
      //////////////////////////////////////////////////////////
      userId: user.id,
      role: user.role,

      //////////////////////////////////////////////////////////
      // ENGINE & LICENSE SCOPE
      //////////////////////////////////////////////////////////
      licenseKey: user.licenseKey ?? null,
      organization: user.organization ?? null,
      engineAccess: user.engineAccess ?? true,
    };

    ////////////////////////////////////////////////////////////
    // ROUTE ACCESS
    ////////////////////////////////////////////////////////////
    const routeAllowed = isApiRoute(pathname)
      ? canAccessApi(auth, pathname, request.method)
      : canAccessRoute(auth, pathname);

    ////////////////////////////////////////////////////////////
    // FORBIDDEN ROUTE
    ////////////////////////////////////////////////////////////
    if (!routeAllowed) {
      return forbidden(request, "Route access denied");
    }

    ////////////////////////////////////////////////////////////
    // POLICY ACCESS
    ////////////////////////////////////////////////////////////
    const policyAllowed = evaluatePolicy({
      path: pathname,
      method: request.method,
      auth,
    });

    ////////////////////////////////////////////////////////////
    // FORBIDDEN POLICY
    ////////////////////////////////////////////////////////////
    if (!policyAllowed) {
      return forbidden(request, "Policy access denied");
    }

    ////////////////////////////////////////////////////////////
    // FORWARD HEADERS
    ////////////////////////////////////////////////////////////
    const headers = new Headers(request.headers);
    headers.set("Cache-Control", "s-maxage=60, stale-while-revalidate");

    ////////////////////////////////////////////////////////////
    // USER
    ////////////////////////////////////////////////////////////
    headers.set("x-auth-user-id", user.id);
    headers.set("x-auth-role", String(user.role));
    headers.set("x-auth-status", String(user.status ?? "ACTIVE"));

    ////////////////////////////////////////////////////////////
    // PROFILE
    ////////////////////////////////////////////////////////////
    headers.set("x-auth-username", user.username ?? "");
    headers.set("x-auth-fullname", user.fullName ?? user.name ?? "");
    headers.set("x-auth-email", user.email ?? "");

    ////////////////////////////////////////////////////////////
    // LICENSE & ENGINE
    ////////////////////////////////////////////////////////////
    headers.set("x-auth-license-key", user.licenseKey ?? "");
    headers.set("x-auth-organization", user.organization ?? "");

    ////////////////////////////////////////////////////////////
    // TOKEN
    ////////////////////////////////////////////////////////////
    headers.set("authorization", `Bearer ${accessToken}`);

    ////////////////////////////////////////////////////////////
    // NEXT
    ////////////////////////////////////////////////////////////
    return NextResponse.next({
      request: {
        headers,
      },
    });
  } catch (error) {
    ////////////////////////////////////////////////////////////
    // LOG
    ////////////////////////////////////////////////////////////
    serverLog("[PROXY_ERROR]", error);

    ////////////////////////////////////////////////////////////
    // RESPONSE
    ////////////////////////////////////////////////////////////
    return NextResponse.json(
      {
        success: false,
        message: "Proxy internal error",
      },
      {
        status: 500,
      },
    );
  }
}

